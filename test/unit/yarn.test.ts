import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, describe, it } from "node:test";
import type { Project } from "../../src/adapters/adapter.ts";
import {
  classicPatternMatches,
  headerDescriptors,
  parseClassicLock,
  parseResolutionKey,
  YarnAdapter,
  yarnLine,
} from "../../src/adapters/yarn/yarn.ts";

const dirs: string[] = [];
after(() => Promise.all(dirs.map((d) => rm(d, { recursive: true, force: true }))));

async function tempDir(files: Record<string, string>): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "retire-overrides-yarn-unit-"));
  dirs.push(dir);
  for (const [path, content] of Object.entries(files)) await writeFile(join(dir, path), content);
  return dir;
}

function project(installed: string): Project {
  return { ecosystem: "yarn", dir: "", manifest: "package.json", lockfile: "yarn.lock", packageManager: { name: "yarn", installed } };
}

const CLASSIC_LOCK = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@s/kit@^2.4.0", "@s/kit@~2.4.0":
  version "2.4.0"
  resolved "https://registry.yarnpkg.com/@s/kit/-/kit-2.4.0.tgz#abc"
  integrity sha512-x==
  dependencies:
    tar-lite "~3.0.0"
  optionalDependencies:
    fsevents "^2.0.0"

tar-lite@~3.0.0:
  version "3.0.5"
  resolved "https://registry.yarnpkg.com/tar-lite/-/tar-lite-3.0.5.tgz#def"
`;

describe("yarn lockfiles", () => {
  it("parses Classic blocks with quoted, scoped and multi-descriptor headers", () => {
    const lock = parseClassicLock(CLASSIC_LOCK);
    const kit = lock.get("@s/kit@~2.4.0")!;
    assert.equal(kit, lock.get("@s/kit@^2.4.0"));
    assert.equal(kit.name, "@s/kit");
    assert.equal(kit.version, "2.4.0");
    assert.deepEqual(kit.dependencies, { "tar-lite": "~3.0.0", fsevents: "^2.0.0" });
    assert.deepEqual([...kit.optional], ["fsevents"]);
    assert.equal(lock.get("tar-lite@~3.0.0")!.version, "3.0.5");
  });

  it("reads an empty yarn.lock as a project with nothing locked yet", async () => {
    const dir = await tempDir({ "package.json": JSON.stringify({ name: "app", dependencies: { a: "^1.0.0" } }), "yarn.lock": "" });
    const graph = await new YarnAdapter().readGraph(project("4.18.1"), dir);
    assert.deepEqual(graph.importers, ["importer:"]);
    assert.equal(graph.nodes.size, 1);
  });

  it("splits Berry headers into descriptors", () => {
    assert.deepEqual(headerDescriptors('"semver@npm:^7.1.3, semver@npm:~7.3.0":'), ["semver@npm:^7.1.3", "semver@npm:~7.3.0"]);
  });

  it("rebuilds Berry edges through parent-scoped resolutions", async () => {
    const dir = await tempDir({
      "package.json": JSON.stringify({ name: "app", dependencies: { kit: "2.4.0", legacy: "^1.0.0" }, resolutions: { "kit/tar-lite": "3.1.4" } }),
      "yarn.lock": [
        "__metadata:\n  version: 10\n",
        '"app@workspace:.":\n  version: 0.0.0-use.local\n  resolution: "app@workspace:."\n  dependencies:\n    kit: "npm:2.4.0"\n    legacy: "npm:^1.0.0"\n',
        '"kit@npm:2.4.0":\n  version: 2.4.0\n  resolution: "kit@npm:2.4.0"\n  dependencies:\n    tar-lite: "npm:~3.0.0"\n',
        '"legacy@npm:^1.0.0":\n  version: 1.0.0\n  resolution: "legacy@npm:1.0.0"\n  dependencies:\n    tar-lite: "npm:^2.0.0"\n',
        '"tar-lite@npm:3.1.4":\n  version: 3.1.4\n  resolution: "tar-lite@npm:3.1.4"\n',
        '"tar-lite@npm:^2.0.0":\n  version: 2.4.1\n  resolution: "tar-lite@npm:2.4.1"\n',
      ].join("\n"),
    });
    const graph = await new YarnAdapter().readGraph(project("4.18.1"), dir);
    assert.equal(graph.nodes.get("kit@npm:2.4.0")!.children.get("tar-lite"), "tar-lite@npm:3.1.4");
    assert.equal(graph.nodes.get("legacy@npm:1.0.0")!.children.get("tar-lite"), "tar-lite@npm:2.4.1");
    // The engine sees plain ranges, not Berry descriptors.
    assert.equal(graph.nodes.get("kit@npm:2.4.0")!.declared!["tar-lite"], "~3.0.0");
  });
});

describe("yarn resolutions", () => {
  it("distinguishes Classic and Berry by version", () => {
    assert.equal(yarnLine("1.22.22"), "classic");
    assert.equal(yarnLine("4.18.1"), "berry");
  });

  it("matches Classic keys as globs over the whole path from the root", () => {
    const seg = (k: string) => parseResolutionKey(k).segments.map((s) => s.name);
    assert.equal(classicPatternMatches(seg("c"), ["a", "b", "c"]), true);
    assert.equal(classicPatternMatches(seg("a/c"), ["a", "b", "c"]), false);
    assert.equal(classicPatternMatches(seg("a/b/c"), ["a", "b", "c"]), true);
    assert.equal(classicPatternMatches(seg("**/b/c"), ["a", "b", "c"]), true);
    assert.equal(classicPatternMatches(seg("a/**/c"), ["a", "b", "c"]), true);
    assert.deepEqual(parseResolutionKey("@s/kit@npm:2/tar-lite").segments, [{ name: "@s/kit", range: "npm:2" }, { name: "tar-lite" }]);
  });

  it("reports what each line ignores or rejects, and writes the key shape each line honors", async () => {
    const resolutions = { "tar-lite": "3.1.4", "**/a/tar-lite": "3.1.4", "a/b/tar-lite": "3.1.4", "tar-lite@~3.0.0": "3.1.4", "x": "patch:x@1#./p.patch" };
    for (const [version, entries, ignored] of [
      ["1.22.22", ["tar-lite", "**/a/tar-lite", "a/b/tar-lite"], ["tar-lite@~3.0.0", "x"]],
      ["4.18.1", ["tar-lite", "tar-lite@~3.0.0"], ["**/a/tar-lite", "a/b/tar-lite", "x"]],
    ] as const) {
      const dir = await tempDir({ "package.json": JSON.stringify({ name: "app", resolutions }) });
      const adapter = new YarnAdapter();
      const found = await adapter.readOverrides(project(version), dir);
      assert.deepEqual(found.entries.map((e) => e.selector), entries, version);
      assert.deepEqual(found.unsupported.map((u) => u.selector), ignored, version);
      const written = await adapter.writeOverride(project(version), dir, { target: { name: "q" }, scope: [{ name: "p" }], value: "1.0.0" });
      assert.equal(written.selector, version.startsWith("1.") ? "**/p/q" : "p/q");
      const data = JSON.parse(await readFile(join(dir, "package.json"), "utf8")) as { resolutions: Record<string, string> };
      assert.equal(data.resolutions[written.selector], "1.0.0");
    }
  });

  it("applies parent scopes the way each line does", async () => {
    const adapter = new YarnAdapter();
    const step = (name: string) => ({ name, version: "1.0.0" });
    const classic = (await adapter.readOverrides(project("1.22.22"), await tempDir({ "package.json": JSON.stringify({ resolutions: { "a/c": "1.0.0" } }) }))).entries[0]!;
    const berry = (await adapter.readOverrides(project("4.18.1"), await tempDir({ "package.json": JSON.stringify({ resolutions: { "b/c": "1.0.0" } }) }))).entries[0]!;
    const deep = { importer: "", steps: [step("a"), step("b"), step("c")] };
    // Classic `a/c` needs c directly under a at the root; Berry `b/c` needs b as the direct parent.
    assert.equal(adapter.overrideApplies(classic, deep), false);
    assert.equal(adapter.overrideApplies(classic, { importer: "", steps: [step("a"), step("c")] }), true);
    assert.equal(adapter.overrideApplies(berry, deep), true);
  });
});
