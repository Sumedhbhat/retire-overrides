// Bundles the CLI into dist/cli.mjs, the file the action and reusable workflow run.
// `--check` fails if the committed bundle is out of date. RETIRE_OVERRIDES_VERSION overrides the
// version stamped into the bundle (release CI uses it for nightly suffixes; the manifest is never edited).
import { readFile, writeFile } from "node:fs/promises";
import { build } from "esbuild";

const check = process.argv.includes("--check");
const manifest = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const version = process.env.RETIRE_OVERRIDES_VERSION ?? manifest.version;
const outfile = new URL("../dist/cli.mjs", import.meta.url);

const result = await build({
  entryPoints: [new URL("../src/cli.ts", import.meta.url).pathname],
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  write: false,
  legalComments: "inline",
  banner: {
    js: "#!/usr/bin/env node\n// Generated by scripts/build.mjs from src/. Do not edit.\nimport { createRequire as __createRequire } from 'node:module'; const require = __createRequire(import.meta.url);",
  },
  define: { __RETIRE_OVERRIDES_VERSION__: JSON.stringify(version) },
});
const code = result.outputFiles[0].text.replace(/^#!.*\n(?=#!)/, "");

if (check) {
  const committed = await readFile(outfile, "utf8").catch(() => "");
  if (committed !== code) {
    console.error("dist/cli.mjs is out of date. Run `npm run build` and commit the result.");
    process.exit(1);
  }
  console.log("dist/cli.mjs is up to date.");
} else {
  await writeFile(outfile, code, { mode: 0o755 });
  console.log(`built dist/cli.mjs (${version})`);
}
