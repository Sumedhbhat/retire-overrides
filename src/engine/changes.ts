import { TRAILER } from "../git.ts";
import type { EngineContext } from "./context.ts";
import { branchFor, groupMarker, marker, selectorKey, staleIdentity } from "./identity.ts";
import type {
  AdvisoryRef,
  ChangeKind,
  InstanceEvidence,
  OverrideReport,
  PlannedChange,
  PlannedIssue,
  VersionEvidence,
  VulnerabilityReport,
} from "./report.ts";
import { toolVersion } from "../version.ts";

export const MAJOR_LABEL = "security-major";
export const TOOL_LABEL = "retire-overrides";

function trailers(identity: string, action: ChangeKind, selectors: string[], advisories: string[]): string {
  return [
    `${TRAILER.id}: ${identity}`,
    `${TRAILER.action}: ${action}`,
    ...selectors.map((s) => `${TRAILER.selector}: ${s}`),
    ...advisories.map((a) => `${TRAILER.advisory}: ${a}`),
  ].join("\n");
}

function advisoryList(advisories: AdvisoryRef[]): string {
  if (advisories.length === 0) return "_No known advisories._";
  return advisories
    .map((a) => {
      const link = a.url ? `[${a.id}](${a.url})` : a.id;
      const title = a.title && a.title !== a.id ? ` — ${a.title}` : "";
      return `- ${link}${title}: affected ${a.ranges.map((r) => `\`${r}\``).join(", ")}${a.severity ? ` (${a.severity})` : ""}`;
    })
    .join("\n");
}

function instanceList(instances: InstanceEvidence[], name: string): string {
  if (instances.length === 0) return `_No copy of ${name} remains in the resolved graph._`;
  return instances
    .map((i) => {
      const status = i.affectedBy.length > 0 ? `affected by ${i.affectedBy.join(", ")}` : "not affected";
      const paths = i.paths.map((p) => `  - \`${p}\``).join("\n");
      return `- \`${name}@${i.version}\` (${status})\n${paths}${i.pathsTruncated ? "\n  - …more paths omitted" : ""}`;
    })
    .join("\n");
}

function versionTable(versions: VersionEvidence[]): string {
  if (versions.length === 0) return "_No newly resolved versions._";
  return [
    "| Package | Version | Published | Age (days) |",
    "|---|---|---|---|",
    ...versions.map((v) => `| \`${v.name}\` | ${v.version} | ${v.published?.slice(0, 10) ?? "unknown"} | ${v.ageDays ?? "?"} |`),
  ].join("\n");
}

function footer(ctx: EngineContext, identity: string, groupKey: string): string {
  return [
    "---",
    `Generated by [retire-overrides](https://github.com/Sumedhbhat/retire-overrides) ${toolVersion()} from commit \`${ctx.options.commit.slice(0, 12)}\`, evaluated at ${ctx.now.toISOString()}.`,
    "Reproduce with `retire-overrides check --now " + ctx.now.toISOString() + "` on that commit. Required CI must pass before this merges.",
    "",
    marker(identity),
    groupMarker(groupKey),
  ].join("\n");
}

export function buildRemovalChange(
  ctx: EngineContext,
  report: OverrideReport,
  patch: string,
  files: string[],
  majorBlockers: string[],
): PlannedChange {
  const name = report.target.name;
  const selector = selectorKey(report.ecosystem, report.file, report.selector);
  const advisories = report.evidence.advisories.map((a) => a.id);
  const title = `chore(deps): remove ${report.ecosystem} override for ${name}`;
  const constraints = (report.evidence.parentConstraints ?? [])
    .map((c) => `- ${c.parent} declares \`${c.dependency}@${c.range}\`, which permits no known vulnerable version`)
    .join("\n");
  const rationale = [
    `Without the override \`${report.selector}\` (${report.file}), every resolved copy of ${name} is outside all known affected ranges,`,
    `no parent constraint still permits a vulnerable version, the audit gains no findings, and every newly resolved version`,
    `is at least ${ctx.config.minimumReleaseAgeDays} days old.`,
  ].join(" ");
  const body = [
    `Removes the override \`${report.selector} → ${report.value}\` from \`${report.file}\`. Upstream no longer needs it.`,
    "",
    "**Status: REMOVABLE**",
    "",
    rationale,
    "",
    "### Resolved copies without the override",
    instanceList(report.evidence.instancesWithoutOverride ?? [], name),
    "",
    "### Parent constraints",
    constraints || "_No parent constraints (the package is no longer depended on)._",
    "",
    "### Known advisories for " + name,
    advisoryList(report.evidence.advisories),
    "",
    "### Newly resolved versions",
    versionTable(report.evidence.changedVersions ?? []),
    ...(majorBlockers.length > 0 ? ["", "### Needs human review", ...majorBlockers.map((b) => `- ${b}`)] : []),
    "",
    provenanceLine(report),
    "",
    footer(ctx, report.identity, report.identity),
    "",
    trailers(report.identity, "remove-override", [selector], advisories),
  ].join("\n");
  const commitMessage = [title, "", rationale, "", trailers(report.identity, "remove-override", [selector], advisories)].join("\n");
  return {
    identity: report.identity,
    groupKey: report.identity,
    kind: "remove-override",
    ecosystem: report.ecosystem,
    project: report.project,
    packages: [name],
    advisories,
    selectors: [selector],
    branch: branchFor("remove-override", [name], report.identity),
    title,
    body,
    commitMessage,
    labels: [...ctx.config.labels, TOOL_LABEL, ...(majorBlockers.length > 0 ? [MAJOR_LABEL] : [])],
    autoMerge: majorBlockers.length === 0,
    autoMergeBlockers: majorBlockers,
    baseCommit: ctx.options.commit,
    changedVersions: report.evidence.changedVersions ?? [],
    files,
    patch,
  };
}

function provenanceLine(report: OverrideReport): string {
  const p = report.provenance;
  const intent =
    report.intent.kind === "tool"
      ? `added by retire-overrides in ${report.intent.commit.slice(0, 12)} for ${report.intent.advisories.join(", ") || "unrecorded advisories"}`
      : report.intent.kind === "managed"
        ? "opted in to automatic management via `manage`"
        : report.intent.kind;
  const when = p.date ? ` on ${p.date.slice(0, 10)}` : "";
  const who = p.author ? ` by ${p.author}` : "";
  return `Override history: ${intent}${p.commit ? `; introduced in ${p.commit.slice(0, 12)}${who}${when}` : ""} (source: ${p.source}).`;
}

export function buildStaleIssue(ctx: EngineContext, report: OverrideReport): PlannedIssue {
  const identity = staleIdentity(report.ecosystem, report.file, report.selector);
  const name = report.target.name;
  const title = `Stale dependency override: ${name} (${report.ecosystem}, ${report.file})`;
  const body = [
    `The override \`${report.selector} → ${report.value}\` in \`${report.file}\` is still needed after ${report.evidence.overrideAgeDays} days (threshold: ${ctx.config.staleAfterDays}).`,
    "",
    "### Why it is still needed",
    ...report.reasons.map((r) => `- ${r.message}`),
    "",
    "### Resolved copies without the override",
    instanceList(report.evidence.instancesWithoutOverride ?? [], name),
    "",
    "### Upstream",
    ...(report.evidence.upstream ?? ["_No upstream release information available._"]).map((u) => `- ${u}`),
    "",
    "### Advisories",
    advisoryList(report.evidence.advisories),
    "",
    "Consider asking the parent's maintainers to widen or raise their range, or replacing the parent. retire-overrides keeps checking daily and opens a removal PR as soon as it is safe.",
    "",
    provenanceLine(report),
    "",
    footer(ctx, identity, identity),
  ].join("\n");
  return { identity, groupKey: identity, title, body, labels: [...ctx.config.labels, TOOL_LABEL] };
}

export interface FixChangeInput {
  kind: Exclude<ChangeKind, "remove-override">;
  identity: string;
  groupKey: string;
  vulnerabilities: VulnerabilityReport[];
  summary: string;
  details: string[];
  selectors: string[];
  changedVersions: VersionEvidence[];
  autoMergeBlockers: string[];
  major: boolean;
  patch: string;
  files: string[];
}

export function buildFixChange(ctx: EngineContext, input: FixChangeInput): PlannedChange {
  const packages = [...new Set(input.vulnerabilities.map((v) => v.package))].sort();
  const advisories = [...new Set(input.vulnerabilities.flatMap((v) => v.advisories.map((a) => a.id)))].sort();
  const ecosystem = input.vulnerabilities[0]!.ecosystem;
  const title = `fix(deps): ${input.summary} for ${advisories.join(", ")}`;
  const sections = input.vulnerabilities.flatMap((v) => [
    `### ${v.package}`,
    "Affected copies before this change:",
    instanceList(v.instances, v.package),
    "",
    "Advisories:",
    advisoryList(v.advisories),
    "",
  ]);
  const alerts = input.vulnerabilities.flatMap((v) => v.alerts ?? []).sort((a, b) => a.number - b.number);
  const attempts = input.vulnerabilities[0]!.attempts
    .map((a) => `- ${a.strategy}: ${a.outcome}${a.reasons.length > 0 ? ` — ${a.reasons.map((r) => r.message).join("; ")}` : ""}`)
    .join("\n");
  const body = [
    `Security fix: ${input.summary}.`,
    "",
    ...input.details.map((d) => `- ${d}`),
    "",
    ...(alerts.length > 0 ? [...alerts.map((a) => `Fixes Dependabot alert [#${a.number}](${a.url}) (${a.advisory}).`), ""] : []),
    "Every affected copy and dependency path was re-resolved without installing packages or running scripts. After this change no copy is in a known affected range and the audit gains no new findings. Repository CI must still pass.",
    "",
    ...sections,
    "### Strategies tried (smallest first)",
    attempts,
    "",
    "### Versions this change resolves",
    versionTable(input.changedVersions),
    ...(input.autoMergeBlockers.length > 0 ? ["", "### Needs human review", ...input.autoMergeBlockers.map((b) => `- ${b}`)] : []),
    "",
    footer(ctx, input.identity, input.groupKey),
    "",
    trailers(input.identity, input.kind, input.selectors, advisories),
  ].join("\n");
  const commitMessage = [
    title,
    "",
    ...input.details,
    "",
    trailers(input.identity, input.kind, input.selectors, advisories),
  ].join("\n");
  return {
    identity: input.identity,
    groupKey: input.groupKey,
    kind: input.kind,
    ecosystem,
    project: input.vulnerabilities[0]!.project,
    packages,
    advisories,
    selectors: input.selectors,
    branch: branchFor(input.kind, packages, input.identity),
    title,
    body,
    commitMessage,
    labels: [...ctx.config.labels, TOOL_LABEL, ...(input.major ? [MAJOR_LABEL] : [])],
    autoMerge: input.autoMergeBlockers.length === 0,
    autoMergeBlockers: input.autoMergeBlockers,
    baseCommit: ctx.options.commit,
    changedVersions: input.changedVersions,
    files: input.files,
    patch: input.patch,
  };
}
